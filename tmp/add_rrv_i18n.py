BASE = os.path.join(os.path.dirname(__file__), '..', 'gui', 'templates', 'i18n')
langs = ['en', 'ro', 'de', 'fr', 'es', 'it', 'pt', 'ja', 'ru', 'zh']
for lang in langs:
    path = os.path.join(BASE, lang + '.json')
    with open(path, 'r', encoding='utf-8') as f:
        data = json.load(f)
    added = 0
    for k, v in KEYS[lang].items():
        if k not in data or data[k] != v:
            data[k] = v
            added += 1
    with open(path, 'w', encoding='utf-8') as f:
        json.dump(data, f, ensure_ascii=False, indent=2)
    print(lang, 'added/updated', added)